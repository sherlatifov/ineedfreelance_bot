import logging

from aiogram import F, Router
from aiogram.fsm.context import FSMContext
from aiogram.fsm.state import State, StatesGroup
from aiogram.types import CallbackQuery, Message

from database.repositories.freelancer_profile import (
    get_or_create_freelancer_profile,
    update_freelancer_title,
)
from database.repositories.user import get_user
from handlers.profile.main import build_freelancer_profile_text
from utils.message import delete_message_safely


# ============================================================
# ROUTER
# ============================================================

router = Router()


# ============================================================
# LOGGER
# ============================================================
#
# Используем logger для того, чтобы видеть в BotHost:
#
# - кто изменяет Title;
# - какой Title был сохранён;
# - какое сообщение профиля нужно вернуть;
# - успешно ли обновился профиль;
# - если произошла ошибка Telegram API.
#
# ============================================================

logger = logging.getLogger(__name__)


# ============================================================
# FSM СОСТОЯНИЯ
# ============================================================
#
# FSM нужен для того, чтобы бот понимал:
#
# "Сейчас пользователь находится в режиме
# редактирования Title".
#
# После нажатия:
#
#     💻 Изменить Title
#
# устанавливается:
#
#     TitleStates.waiting_for_title
#
# После получения Title состояние очищается.
#
# ВАЖНО:
# Каждый раздел профиля имеет свои состояния.
# Мы специально НЕ выносим их в общий states.py.
#
# ============================================================


class TitleStates(StatesGroup):
    """
    FSM-состояния для редактирования Title.
    """

    waiting_for_title = State()


# ============================================================
# НАЖАТИЕ «ИЗМЕНИТЬ TITLE»
# ============================================================
#
# Пользователь находится на странице:
#
#     👨‍💻 Мой профиль
#
# и нажимает:
#
#     💻 Изменить Title
#
# Мы НЕ создаём новое сообщение.
#
# Мы запоминаем ID текущего сообщения профиля,
# а затем превращаем это же сообщение в экран:
#
#     💻 Изменение Title
#
# После ввода Title мы сможем снова изменить
# именно это сообщение и вернуть профиль.
#
# ============================================================


@router.callback_query(F.data == "profile:edit_title")
async def edit_profile_title(
    callback: CallbackQuery,
    state: FSMContext,
):
    """
    Открывает экран редактирования Title.
    """

    # --------------------------------------------------------
    # 1. Получаем пользователя
    # --------------------------------------------------------
    #
    # callback.from_user.id — это Telegram ID.
    #
    # Например:
    #
    #     Telegram ID = 8631787760
    #
    # get_user() ищет пользователя именно по Telegram ID.
    #
    # --------------------------------------------------------

    user = await get_user(
        callback.from_user.id
    )

    if user is None:
        await callback.answer(
            "Пользователь не найден.",
            show_alert=True,
        )
        return

    # --------------------------------------------------------
    # 2. Проверяем, что сообщение существует
    # --------------------------------------------------------
    #
    # Нам обязательно нужно текущее сообщение профиля,
    # потому что именно его мы будем редактировать.
    #
    # --------------------------------------------------------

    if callback.message is None:
        await callback.answer(
            "Не удалось открыть редактирование.",
            show_alert=True,
        )
        return

    # --------------------------------------------------------
    # 3. Сохраняем ID сообщения профиля
    # --------------------------------------------------------
    #
    # Например:
    #
    #     profile_message_id = 263
    #
    # Сейчас сообщение 263 выглядит как профиль.
    #
    # Мы временно превратим его в:
    #
    #     💻 Изменение Title
    #
    # А после ввода Title снова отредактируем
    # сообщение №263 и вернём профиль.
    #
    # --------------------------------------------------------

    await state.update_data(
        profile_message_id=callback.message.message_id,
    )

    # --------------------------------------------------------
    # 4. Переводим пользователя в FSM-состояние
    # --------------------------------------------------------
    #
    # Теперь следующее обычное текстовое сообщение
    # пользователя будет обработано функцией:
    #
    #     process_profile_title()
    #
    # --------------------------------------------------------

    await state.set_state(
        TitleStates.waiting_for_title
    )

    # Убираем "часики" с inline-кнопки Telegram.
    await callback.answer()

    # --------------------------------------------------------
    # 5. Меняем текущее сообщение профиля
    #    на экран ввода Title
    # --------------------------------------------------------

    await callback.message.edit_text(
        "💻 <b>Изменение Title</b>\n\n"
        "Введите ваш профессиональный Title.\n\n"
        "Например:\n"
        "<code>Python Backend Developer</code>\n\n"
        "Максимум — 255 символов.",
        parse_mode="HTML",
    )


# ============================================================
# ПОЛЬЗОВАТЕЛЬ ВВОДИТ TITLE
# ============================================================
#
# Эта функция вызывается только тогда, когда пользователь
# находится в состоянии:
#
#     TitleStates.waiting_for_title
#
# Например пользователь отправляет:
#
#     Дизайнер
#
# ============================================================


@router.message(TitleStates.waiting_for_title)
async def process_profile_title(
    message: Message,
    state: FSMContext,
):
    """
    Получает и сохраняет новый Title.

    После сохранения:
    
        1. Обновляем PostgreSQL
        2. Получаем актуальный профиль
        3. Удаляем сообщение пользователя
        4. Возвращаем профиль в то же сообщение
        5. Возвращаем inline-клавиатуру профиля
    """

    logger.info(
        "Получен новый Title от пользователя %s",
        message.from_user.id,
    )

    # ========================================================
    # 1. ПРОВЕРЯЕМ, ЧТО ПРИШЁЛ ТЕКСТ
    # ========================================================
    #
    # Title должен быть обычным текстовым сообщением.
    #
    # Если пользователь отправит фотографию, стикер и т.д.,
    # message.text будет None.
    #
    # ========================================================

    if not message.text:
        await message.answer(
            "❌ Пожалуйста, отправьте Title "
            "обычным текстовым сообщением."
        )
        return

    # Убираем пробелы в начале и конце.
    title = message.text.strip()

    # ========================================================
    # 2. ПРОВЕРЯЕМ ДЛИНУ TITLE
    # ========================================================

    if len(title) < 2:
        await message.answer(
            "❌ Title слишком короткий.\n\n"
            "Минимум — 2 символа."
        )
        return

    if len(title) > 255:
        await message.answer(
            "❌ Title слишком длинный.\n\n"
            "Максимум — 255 символов."
        )
        return

    # ========================================================
    # 3. ПОЛУЧАЕМ ПОЛЬЗОВАТЕЛЯ
    # ========================================================
    #
    # Здесь:
    #
    #     message.from_user.id
    #
    # это Telegram ID.
    #
    # Например:
    #
    #     8631787760
    #
    # get_user() находит по нему пользователя.
    #
    # ========================================================

    user = await get_user(
        message.from_user.id
    )

    if user is None:
        await state.clear()

        await message.answer(
            "❌ Пользователь не найден.\n\n"
            "Пожалуйста, выполните /start."
        )

        return

    # ========================================================
    # 4. ПОЛУЧАЕМ FREELANCER PROFILE
    # ========================================================
    #
    # Здесь уже используем:
    #
    #     user.id
    #
    # Это ВНУТРЕННИЙ ID пользователя в PostgreSQL.
    #
    # Например:
    #
    #     user.id = 1
    #
    # Связь получается:
    #
    #     users.id
    #          ↓
    #     freelancer_profiles.user_id
    #
    # ========================================================

    await get_or_create_freelancer_profile(
        user_id=user.id,
    )

    # ========================================================
    # 5. СОХРАНЯЕМ TITLE В POSTGRESQL
    # ========================================================
    #
    # update_freelancer_title() получает:
    #
    #     user_id = внутренний ID PostgreSQL
    #
    #     title = новый Title
    #
    # ========================================================

    profile = await update_freelancer_title(
        user_id=user.id,
        title=title,
    )

    if profile is None:
        await state.clear()

        await message.answer(
            "❌ Не удалось сохранить Title."
        )

        return

    logger.info(
        "Title успешно сохранён: user_id=%s title=%r",
        user.id,
        title,
    )

    # ========================================================
    # 6. ПОЛУЧАЕМ ID СООБЩЕНИЯ ПРОФИЛЯ
    # ========================================================
    #
    # Когда пользователь нажал:
    #
    #     💻 Изменить Title
    #
    # мы сохранили:
    #
    #     profile_message_id
    #
    # Например:
    #
    #     profile_message_id = 263
    #
    # Это сообщение сейчас содержит:
    #
    #     💻 Изменение Title
    #
    # Именно его мы позже превратим обратно в профиль.
    #
    # ========================================================

    data = await state.get_data()

    profile_message_id = data.get(
        "profile_message_id"
    )

    logger.info(
        "profile_message_id=%s",
        profile_message_id,
    )

    # ========================================================
    # 7. ОЧИЩАЕМ FSM
    # ========================================================
    #
    # Title уже получен и сохранён.
    #
    # Пользователь больше не находится в режиме:
    #
    #     waiting_for_title
    #
    # ========================================================

    await state.clear()

    # ========================================================
    # 8. УДАЛЯЕМ СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ
    # ========================================================
    #
    # Пользователь отправил:
    #
    #     Дизайнер
    #
    # После обработки это сообщение нам больше не нужно.
    #
    # Удаляем его, чтобы чат оставался чистым.
    #
    # ========================================================

    await delete_message_safely(
        bot=message.bot,
        chat_id=message.chat.id,
        message_id=message.message_id,
    )

    # ========================================================
    # 9. СТРОИМ АКТУАЛЬНЫЙ ПРОФИЛЬ
    # ========================================================
    #
    # ВАЖНЫЙ МОМЕНТ!
    #
    # build_freelancer_profile_text() теперь принимает
    # именно Telegram ID:
    #
    #     telegram_id
    #
    # НЕ:
    #
    #     user.id
    #
    # Почему?
    #
    # user.id:
    #
    #     1
    #
    # это внутренний ID PostgreSQL.
    #
    # message.from_user.id:
    #
    #     8631787760
    #
    # это Telegram ID.
    #
    # Функция get_user() ищет именно по Telegram ID.
    #
    # ========================================================

    result = await build_freelancer_profile_text(
        telegram_id=message.from_user.id,
    )

    # --------------------------------------------------------
    # Если профиль не удалось построить
    # --------------------------------------------------------

    if result is None:

        logger.error(
            "Не удалось построить профиль: telegram_id=%s",
            message.from_user.id,
        )

        # Title уже сохранён в PostgreSQL.
        # Поэтому сообщаем пользователю об этом,
        # даже если возникла проблема с отображением.
        await message.answer(
            "✅ Title успешно сохранён.\n\n"
            "Но не удалось обновить отображение профиля."
        )

        return

    # Получаем:
    #
    #     profile_text
    #     keyboard
    #
    profile_text, keyboard = result

    # ========================================================
    # 10. ДОБАВЛЯЕМ УВЕДОМЛЕНИЕ
    # ========================================================
    #
    # Не создаём отдельное сообщение.
    #
    # Добавляем уведомление непосредственно
    # в верхнюю часть профиля.
    #
    # В результате пользователь увидит:
    #
    #     ✅ Title успешно изменён!
    #
    #     👨‍💻 Мой профиль
    #
    #     ...
    #
    # ========================================================

    final_text = (
        "✅ <b>Title успешно изменён!</b>\n\n"
        + profile_text
    )

    # ========================================================
    # 11. ВОЗВРАЩАЕМ ПРОФИЛЬ
    # ========================================================
    #
    # Если мы ранее сохранили ID сообщения профиля,
    # редактируем именно его.
    #
    # То есть:
    #
    #     было:
    #
    #     💻 Изменение Title
    #
    #     станет:
    #
    #     ✅ Title успешно изменён!
    #
    #     👨‍💻 Мой профиль
    #
    #     + клавиатура профиля
    #
    # ========================================================

    if profile_message_id is not None:

        try:

            await message.bot.edit_message_text(
                chat_id=message.chat.id,
                message_id=profile_message_id,
                text=final_text,
                parse_mode="HTML",
                reply_markup=keyboard,
            )

            logger.info(
                "Профиль успешно обновлён после изменения Title. "
                "telegram_id=%s message_id=%s",
                message.from_user.id,
                profile_message_id,
            )

            return

        except Exception:

            # ------------------------------------------------
            # Если Telegram не смог изменить сообщение,
            # сохраняем полный traceback в логах.
            #
            # Это очень важно для диагностики.
            #
            # Например, Telegram может вернуть:
            #
            #     message to edit not found
            #
            #     message can't be edited
            #
            # и т.д.
            #
            # ------------------------------------------------

            logger.exception(
                "ОШИБКА при возврате на профиль. "
                "telegram_id=%s message_id=%s",
                message.from_user.id,
                profile_message_id,
            )

    # ========================================================
    # 12. FALLBACK
    # ========================================================
    #
    # Если по какой-либо причине старое сообщение
    # невозможно отредактировать, создаём новое сообщение
    # с уже обновлённым профилем.
    #
    # Это запасной вариант.
    #
    # В нормальной ситуации этот код выполняться НЕ должен.
    #
    # ========================================================

    await message.answer(
        text=final_text,
        parse_mode="HTML",
        reply_markup=keyboard,
    )