import logging

from aiogram import F, Router
from aiogram.fsm.context import FSMContext
from aiogram.fsm.state import State, StatesGroup
from aiogram.types import CallbackQuery, Message

from database.repositories.freelancer_profile import (
    get_or_create_freelancer_profile,
    update_freelancer_bio,
)
from database.repositories.user import get_user
from handlers.profile.main import build_freelancer_profile_text
from utils.message import delete_message_safely


# ============================================================
# ROUTER
# ============================================================
#
# Отдельный Router для раздела:
#
#     📝 О себе
#
# ============================================================

router = Router()


# ============================================================
# LOGGER
# ============================================================
#
# Через logger будем видеть в BotHost:
#
# - кто изменил Bio;
# - какой пользователь был найден;
# - успешно ли сохранилось Bio;
# - какое сообщение профиля нужно вернуть;
# - успешно ли обновился экран профиля.
#
# ============================================================

logger = logging.getLogger(__name__)


# ============================================================
# FSM СОСТОЯНИЯ
# ============================================================
#
# После нажатия:
#
#     📝 О себе
#
# пользователь переходит в состояние:
#
#     BioStates.waiting_for_bio
#
# Следующее текстовое сообщение будет восприниматься
# как новое описание пользователя.
#
# ============================================================


class BioStates(StatesGroup):
    """
    FSM-состояния для редактирования Bio.
    """

    waiting_for_bio = State()


# ============================================================
# НАЖАТИЕ «📝 О СЕБЕ»
# ============================================================
#
# Пользователь находится на странице профиля:
#
#     👨‍💻 Мой профиль
#
# и нажимает:
#
#     📝 О себе
#
# Мы не создаём новое сообщение.
#
# Сначала запоминаем ID текущего сообщения профиля.
#
# Например:
#
#     profile_message_id = 270
#
# Затем это же сообщение превращаем в:
#
#     📝 О себе
#
# После ввода текста снова отредактируем сообщение №270
# и вернём туда полноценный профиль.
#
# ============================================================


@router.callback_query(F.data == "profile:edit_bio")
async def edit_profile_bio(
    callback: CallbackQuery,
    state: FSMContext,
):
    """
    Открывает экран редактирования Bio.
    """

    # --------------------------------------------------------
    # 1. Получаем пользователя
    # --------------------------------------------------------
    #
    # callback.from_user.id — Telegram ID пользователя.
    #
    # Например:
    #
    #     8631787760
    #
    # get_user() ищет пользователя именно по этому ID.
    #
    # --------------------------------------------------------

    user = await get_user(
        callback.from_user.id
    )

    if user is None:
        await callback.answer(
            "Пользователь не найден.",
            show_alert=True,
        )
        return

    # --------------------------------------------------------
    # 2. Проверяем наличие сообщения
    # --------------------------------------------------------
    #
    # Нам нужно текущее сообщение профиля,
    # потому что после сохранения Bio мы хотим
    # вернуть профиль именно в него.
    #
    # --------------------------------------------------------

    if callback.message is None:
        await callback.answer(
            "Не удалось открыть редактирование.",
            show_alert=True,
        )
        return

    # --------------------------------------------------------
    # 3. Сохраняем ID сообщения профиля
    # --------------------------------------------------------
    #
    # Например:
    #
    #     profile_message_id = 270
    #
    # Сейчас сообщение 270 содержит профиль.
    #
    # После этого мы изменим его на экран ввода Bio.
    #
    # После получения Bio снова изменим сообщение 270
    # обратно на профиль.
    #
    # --------------------------------------------------------

    await state.update_data(
        profile_message_id=callback.message.message_id,
    )

    # --------------------------------------------------------
    # 4. Устанавливаем FSM-состояние
    # --------------------------------------------------------
    #
    # Теперь бот ожидает обычное текстовое сообщение
    # пользователя с описанием "О себе".
    #
    # --------------------------------------------------------

    await state.set_state(
        BioStates.waiting_for_bio
    )

    await callback.answer()

    # --------------------------------------------------------
    # 5. Показываем экран ввода Bio
    # --------------------------------------------------------
    #
    # Редактируем существующее сообщение профиля.
    #
    # Новое сообщение НЕ создаём.
    #
    # --------------------------------------------------------

    await callback.message.edit_text(
        "📝 <b>О себе</b>\n\n"
        "Расскажите немного о себе, "
        "вашем опыте и специализации.\n\n"
        "Например:\n"
        "<code>Я веб-дизайнер с опытом более 3 лет. "
        "Создаю современные интерфейсы для сайтов "
        "и мобильных приложений.</code>\n\n"
        "Максимум — 2000 символов.",
        parse_mode="HTML",
    )


# ============================================================
# ПОЛЬЗОВАТЕЛЬ ВВОДИТ BIO
# ============================================================
#
# Эта функция срабатывает только тогда, когда пользователь
# находится в:
#
#     BioStates.waiting_for_bio
#
# Например пользователь отправляет:
#
#     Я дизайнер с опытом более 3 лет...
#
# ============================================================


@router.message(BioStates.waiting_for_bio)
async def process_profile_bio(
    message: Message,
    state: FSMContext,
):
    """
    Получает и сохраняет новое Bio.

    После успешного сохранения:

        1. Сохраняем Bio в PostgreSQL
        2. Получаем актуальный профиль
        3. Удаляем сообщение пользователя
        4. Возвращаем профиль в то же сообщение
        5. Возвращаем inline-клавиатуру профиля
    """

    logger.info(
        "Получено новое Bio от пользователя %s",
        message.from_user.id,
    )

    # ========================================================
    # 1. ПРОВЕРЯЕМ, ЧТО ПРИШЁЛ ТЕКСТ
    # ========================================================
    #
    # Bio должно быть обычным текстовым сообщением.
    #
    # Если пользователь отправил фотографию, стикер и т.д.,
    # message.text будет None.
    #
    # ========================================================

    if not message.text:
        await message.answer(
            "❌ Пожалуйста, отправьте информацию "
            "«О себе» обычным текстовым сообщением."
        )
        return

    # Убираем пробелы в начале и конце текста.
    bio = message.text.strip()

    # ========================================================
    # 2. ПРОВЕРЯЕМ ДЛИНУ BIO
    # ========================================================

    if len(bio) < 2:
        await message.answer(
            "❌ Текст слишком короткий.\n\n"
            "Введите минимум 2 символа."
        )
        return

    if len(bio) > 2000:
        await message.answer(
            "❌ Текст слишком длинный.\n\n"
            "Максимальная длина — 2000 символов."
        )
        return

    # ========================================================
    # 3. ПОЛУЧАЕМ ПОЛЬЗОВАТЕЛЯ
    # ========================================================
    #
    # message.from_user.id — Telegram ID.
    #
    # Например:
    #
    #     8631787760
    #
    # get_user() ищет именно по Telegram ID.
    #
    # ========================================================

    user = await get_user(
        message.from_user.id
    )

    if user is None:
        await state.clear()

        await message.answer(
            "❌ Пользователь не найден.\n\n"
            "Пожалуйста, выполните /start."
        )

        return

    # ========================================================
    # 4. ПОЛУЧАЕМ FREELANCER PROFILE
    # ========================================================
    #
    # Здесь используется уже:
    #
    #     user.id
    #
    # Это внутренний ID пользователя PostgreSQL.
    #
    # Например:
    #
    #     user.id = 1
    #
    # freelancer_profiles.user_id также будет равен 1.
    #
    # ========================================================

    await get_or_create_freelancer_profile(
        user_id=user.id,
    )

    # ========================================================
    # 5. СОХРАНЯЕМ BIO В POSTGRESQL
    # ========================================================
    #
    # update_freelancer_bio() изменит:
    #
    #     freelancer_profiles.bio
    #
    # ========================================================

    profile = await update_freelancer_bio(
        user_id=user.id,
        bio=bio,
    )

    if profile is None:
        await state.clear()

        await message.answer(
            "❌ Не удалось сохранить информацию «О себе»."
        )

        return

    logger.info(
        "Bio успешно сохранено: user_id=%s",
        user.id,
    )

    # ========================================================
    # 6. ПОЛУЧАЕМ ID СООБЩЕНИЯ ПРОФИЛЯ
    # ========================================================
    #
    # Когда пользователь нажал:
    #
    #     📝 О себе
    #
    # мы сохранили ID сообщения профиля.
    #
    # Например:
    #
    #     profile_message_id = 270
    #
    # Именно его будем возвращать обратно в профиль.
    #
    # ========================================================

    data = await state.get_data()

    profile_message_id = data.get(
        "profile_message_id"
    )

    logger.info(
        "profile_message_id=%s",
        profile_message_id,
    )

    # ========================================================
    # 7. ОЧИЩАЕМ FSM
    # ========================================================
    #
    # Bio уже получено.
    #
    # Пользователь больше не находится
    # в состоянии waiting_for_bio.
    #
    # ========================================================

    await state.clear()

    # ========================================================
    # 8. УДАЛЯЕМ СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ
    # ========================================================
    #
    # Например пользователь отправил:
    #
    #     Я дизайнер с опытом более 3 лет...
    #
    # После сохранения это сообщение нам больше не нужно.
    #
    # Поэтому удаляем его.
    #
    # ========================================================

    await delete_message_safely(
        bot=message.bot,
        chat_id=message.chat.id,
        message_id=message.message_id,
    )

    # ========================================================
    # 9. СТРОИМ ОБНОВЛЁННЫЙ ПРОФИЛЬ
    # ========================================================
    #
    # ВАЖНО!
    #
    # build_freelancer_profile_text() принимает:
    #
    #     telegram_id
    #
    # Поэтому передаём:
    #
    #     message.from_user.id
    #
    # А НЕ:
    #
    #     user.id
    #
    # Потому что:
    #
    # user.id                 = ID PostgreSQL
    # message.from_user.id    = Telegram ID
    #
    # ========================================================

    result = await build_freelancer_profile_text(
        telegram_id=message.from_user.id,
    )

    if result is None:

        logger.error(
            "Не удалось построить профиль: telegram_id=%s",
            message.from_user.id,
        )

        # Bio уже сохранено в PostgreSQL.
        # Поэтому сообщаем пользователю, что данные
        # не потерялись, даже если экран профиля
        # по какой-то причине не удалось обновить.
        await message.answer(
            "✅ Информация «О себе» сохранена.\n\n"
            "Но не удалось обновить отображение профиля."
        )

        return

    # Получаем готовый текст профиля
    # и клавиатуру профиля.
    profile_text, keyboard = result

    # ========================================================
    # 10. ДОБАВЛЯЕМ УВЕДОМЛЕНИЕ ОБ УСПЕШНОМ ИЗМЕНЕНИИ
    # ========================================================
    #
    # Не отправляем отдельное сообщение.
    #
    # Просто добавляем уведомление в начало
    # существующего сообщения профиля.
    #
    # ========================================================

    final_text = (
        "✅ <b>Информация «О себе» успешно изменена!</b>\n\n"
        + profile_text
    )

    # ========================================================
    # 11. ВОЗВРАЩАЕМ ПРОФИЛЬ В ТО ЖЕ СООБЩЕНИЕ
    # ========================================================
    #
    # Было:
    #
    #     📝 О себе
    #
    # Стало:
    #
    #     ✅ Информация «О себе» успешно изменена!
    #
    #     👨‍💻 Мой профиль
    #
    #     👨‍💻 Имя
    #
    #     💻 Title
    #
    #     ...
    #
    # И снова появляются все кнопки:
    #
    #     ✏️ Изменить имя
    #     💻 Изменить Title
    #     📝 О себе
    #     🛠 Навыки
    #     💰 Ставка
    #     💬 Читать отзывы
    #     ⬅️ Назад
    #
    # ========================================================

    if profile_message_id is not None:

        try:

            await message.bot.edit_message_text(
                chat_id=message.chat.id,
                message_id=profile_message_id,
                text=final_text,
                parse_mode="HTML",
                reply_markup=keyboard,
            )

            logger.info(
                "Профиль успешно обновлён после изменения Bio. "
                "telegram_id=%s message_id=%s",
                message.from_user.id,
                profile_message_id,
            )

            return

        except Exception:

            # ------------------------------------------------
            # Если Telegram не смог изменить сообщение,
            # сохраняем полный traceback в логах BotHost.
            #
            # Это позволит точно понять причину ошибки.
            # ------------------------------------------------

            logger.exception(
                "ОШИБКА при возврате на профиль после Bio. "
                "telegram_id=%s message_id=%s",
                message.from_user.id,
                profile_message_id,
            )

    # ========================================================
    # 12. FALLBACK
    # ========================================================
    #
    # Если старое сообщение невозможно изменить,
    # отправляем новый профиль.
    #
    # В обычной ситуации этот код выполняться не должен.
    #
    # ========================================================

    await message.answer(
        text=final_text,
        parse_mode="HTML",
        reply_markup=keyboard,
    )